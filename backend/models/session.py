import time
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field
from backend.schemas.candidate import CandidateProfile
from backend.schemas.roadmap import InterviewRoadmap

class InterviewSession(BaseModel):
    sessionId: str = Field(..., description="Unique interview session ID")
    candidate: CandidateProfile = Field(..., description="Candidate profile data")
    roadmap: Optional[InterviewRoadmap] = Field(None, description="Interview roadmap generated by Planner")
    current_question: Optional[str] = Field(None, description="Current active interviewer question")
    current_question_index: int = Field(0, description="Index of current question in roadmap (0 to 7)")
    previous_questions: List[str] = Field(default_factory=list, description="List of questions previously asked")
    candidate_responses: List[str] = Field(default_factory=list, description="List of candidate responses received")
    evaluation_history: List[Dict[str, Any]] = Field(default_factory=list, description="Evaluation results for each turn")
    covered_days: List[int] = Field(default_factory=list, description="Curriculum days covered so far")
    turn_history: List[Dict[str, Any]] = Field(default_factory=list, description="Structured history of turns")
    is_completed: bool = Field(False, description="Whether the interview session is finished")
    created_at: float = Field(default_factory=time.time, description="Creation timestamp")
    updated_at: float = Field(default_factory=time.time, description="Last update timestamp")

    def update_timestamp(self) -> None:
        """Update last modified timestamp."""
        self.updated_at = time.time()
